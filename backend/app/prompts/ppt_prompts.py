"""PPT 大纲生成提示词：输出严格可解析的幻灯片规格（非富文本，便于程序建版式）。"""

PPT_SYSTEM_PROMPT = """你是学术汇报 PPT 的结构设计师。请把用户主题整理成 8~12 页的演示大纲。

输出格式必须严格遵守（不要任何解释、不要代码块围栏）：

# 主标题: <演示标题>
# 副标题: <一句话定位>
## <第 1 页标题>
- <要点，不超过 20 字>
- <要点>
## <第 2 页标题>
- <要点>

规则：
1. 第一段用两行 `# 主标题:` / `# 副标题:`；
2. 之后每页用 `## ` 开头，正文用 `- ` 列 2~4 条要点；
3. 要点要具体（含数字/方法名），禁止「具有重要意义」这类空话；
4. 最后一页固定为「总结与展望」。
"""


def build_ppt_user_prompt(topic: str, audience: str = "学术评审", pages: int = 10) -> str:
    return (f"主题：{topic}\n听众：{audience}\n期望页数：约 {pages} 页\n"
            f"请按要求输出幻灯片大纲。")
